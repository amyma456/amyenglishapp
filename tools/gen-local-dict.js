// tools/gen-local-dict.js —— 生成「点词秒出中文」的本地词典
//
// 家长 2026-11-11：「点了单词之后能很快听到发音，但是解释还是正在查询，
// 还需要从云端调数据。这个也搞到本地，不需要联网」。
//
// 做法：把题库（data.js）里出现过的**每一个英文单词**的中文释义 + 音标一次性
// 抓下来，写进 api.js 的 LOCAL_DICT 常量。以后孩子点词，查的是随页面一起
// 下载的本地表，零网络请求；查不到的（课外新词）才保留原来的网络兜底。
//
// 用法：node tools/gen-local-dict.js          （抓数据 + 注入 api.js）
//       node tools/gen-local-dict.js --stats  （只看统计，不写文件）
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUT_JSON = path.join(__dirname, 'local-dict-data.json');
const API_FILE = path.join(ROOT, 'public/api.js');
const BEGIN = '// ===== LOCAL_DICT BEGIN (generated by tools/gen-local-dict.js) =====';
const END = '// ===== LOCAL_DICT END =====';

// ① 题库里所有英文字符串 → 词表
function collectWords() {
  const dataSrc = fs.readFileSync(path.join(ROOT, 'public/data.js'), 'utf8');
  const sandbox = { console, window: {}, document: {}, localStorage: { getItem() { return null; }, setItem() {} } };
  vm.createContext(sandbox);
  vm.runInContext(dataSrc + '\n;this.__W = (typeof HOMEWORK_WEEKS !== "undefined") ? HOMEWORK_WEEKS : null;', sandbox);
  const weeks = sandbox.__W || [];

  const texts = [];
  function walk(o) {
    if (o == null) return;
    if (typeof o === 'string') { if (/[a-z]/.test(o) && !/^https?:|^data:/.test(o)) texts.push(o); return; }
    if (Array.isArray(o)) { o.forEach(walk); return; }
    if (typeof o === 'object') Object.keys(o).forEach(k => walk(o[k]));
  }
  walk(weeks);

  const set = new Set();
  texts.forEach(t => {
    (t.match(/[A-Za-z][A-Za-z'\-]*/g) || []).forEach(w => {
      const k = w.toLowerCase().replace(/^'+|'+$/g, '').replace(/-+$/g, '');
      if (/^[a-z][a-z'\-]{0,19}$/.test(k) && !/['\-]{2}/.test(k)) set.add(k);
    });
  });
  // 短语表 / 变形表里的词也要收（它们会出现在解释里）
  const apiSrc = fs.readFileSync(API_FILE, 'utf8');
  const s = apiSrc.indexOf('const WordHelp = {');
  const e = apiSrc.indexOf('\n};', s) + 3;
  const WordHelp = vm.runInNewContext(apiSrc.slice(s, e) + '\nWordHelp;', { console });
  (WordHelp.PHRASES || []).forEach(p => String(p[0]).split(/\s+/).forEach(w => {
    const k = w.toLowerCase(); if (/^[a-z][a-z'\-]{0,19}$/.test(k)) set.add(k);
  }));
  Object.keys(WordHelp.V || {}).forEach(w => set.add(w));
  return [...set].sort();
}

// ② 题库词汇卡里的中文更贴合课文，优先用
function collectCardZh() {
  const dataSrc = fs.readFileSync(path.join(ROOT, 'public/data.js'), 'utf8');
  const sandbox = { console, window: {}, document: {}, localStorage: { getItem() { return null; }, setItem() {} } };
  vm.createContext(sandbox);
  vm.runInContext(dataSrc + '\n;this.__W = (typeof HOMEWORK_WEEKS !== "undefined") ? HOMEWORK_WEEKS : null;', sandbox);
  const map = {};
  (sandbox.__W || []).forEach(wk => (wk || []).forEach(d => (d.modules || []).forEach(m =>
    (m.words || []).forEach(w => {
      if (w && w.word && w.meaning) {
        const k = String(w.word).toLowerCase().trim();
        if (!map[k]) map[k] = { zh: String(w.meaning).trim(), phon: String(w.phonetic || '').replace(/^\/|\/$/g, '') };
      }
    }))));
  return map;
}

async function fetchOne(w) {
  const url = 'https://amyeng.top/api/dict?word=' + encodeURIComponent(w);
  for (let a = 0; a < 2; a++) {
    try {
      const r = await fetch(url, { signal: AbortSignal.timeout(12000) });
      if (!r.ok) throw new Error('HTTP ' + r.status);
      const j = await r.json();
      return { phon: String(j.phon || '').trim(), zh: String(j.zh || '').trim() };
    } catch (e) { /* 重试一次 */ }
  }
  return null;
}

// 把有道那一长串义项压成给孩子看的一条短释义。
// "adj. （尺寸、范围、容量）大的；广泛的，重要的；…" → "大的"
function cleanZh(raw) {
  let s = String(raw || '').trim();
  if (!s) return '';
  s = s.replace(/^[a-zA-Z]+\.+\s*/, '');          // 词性前缀 adj. / n. / v.
  s = s.replace(/[（(][^）)]*[）)]/g, '');         // 先整段去掉括号（尺寸、范围、容量）
  s = s.split(/[;；]/)[0].split(/[,，、]/)[0];    // 再取第一个义项的第一小段
  s = s.replace(/……/g, '').replace(/^[）)、，,；;\s]+/, '').replace(/\s+/g, ' ').trim();
  if (!s) return String(raw).split(/[;；]/)[0].replace(/^[a-zA-Z]+\.+\s*/, '').trim().slice(0, 12);
  return s.length <= 14 ? s : s.slice(0, 14);
}

// 题库里混进来的模块 id（mon-vocab / fri-mcq …）不是英文单词，不收。
function isRealWord(w) {
  if (!/^[a-z][a-z'\-]{0,19}$/.test(w)) return false;
  if (/^(mon|tue|wed|thu|fri|sat|sun|w[0-9])-/.test(w)) return false;
  if (/(choice|grammar|vocab|speaking|reading|listening|writing|cloze|mcq|fill|blank|plural|tense)$/.test(w) && w.indexOf('-') > 0) return false;
  return true;
}

async function main() {
  const statsOnly = process.argv.indexOf('--stats') >= 0;
  const reuse = process.argv.indexOf('--reuse') >= 0;
  const words = collectWords().filter(isRealWord);
  const card = collectCardZh();
  console.log('词表:', words.length, ' 词汇卡自带:', Object.keys(card).length);

  const result = {};
  let fromCard = 0;
  words.forEach(w => {
    if (card[w] && card[w].zh) { result[w] = card[w]; fromCard++; }
  });
  const todo = words.filter(w => !result[w]);
  console.log('需要联网抓:', todo.length, '（词汇卡已覆盖', fromCard, '）');

  if (reuse && fs.existsSync(OUT_JSON)) {
    const old = JSON.parse(fs.readFileSync(OUT_JSON, 'utf8'));
    Object.keys(old).forEach(k => { if (isRealWord(k)) result[k] = old[k]; });
    console.log('--reuse：复用已有抓取结果', Object.keys(result).length, '条，跳过网络');
  } else {
  let done = 0, ok = 0, fail = 0;
  const CONC = 8;
  let cursor = 0;
  await Promise.all(Array.from({ length: CONC }, async () => {
    while (cursor < todo.length) {
      const w = todo[cursor++];
      const r = await fetchOne(w);
      done++;
      if (r && r.zh) { result[w] = r; ok++; }
      else if (r) { result[w] = { phon: r.phon, zh: '' }; fail++; }
      else fail++;
      if (done % 200 === 0) console.log('  progress', done, '/', todo.length, ' ok', ok, ' empty', fail);
    }
  }));
  }

  const withZh = Object.keys(result).filter(k => result[k].zh);
  console.log('抓完：有中文', withZh.length, '/', words.length,
    '=', (withZh.length / words.length * 100).toFixed(1) + '%', ' 空/失败', words.length - withZh.length);
  if (statsOnly) {
    console.log('无中文示例:', words.filter(w => !result[w] || !result[w].zh).slice(0, 80).join(' '));
    return;
  }
  fs.writeFileSync(OUT_JSON, JSON.stringify(result, null, 0), 'utf8');
  console.log('已写', OUT_JSON, fs.statSync(OUT_JSON).size, 'bytes');

  // ③ 注入 api.js（重复运行会替换掉上一段）
  // 紧凑格式：word → "短中文|音标"。中文先清洗过，孩子点开一眼看完，
  // 文件也从 560KB 压到 100KB 上下（gzip 后更小）。
  const compact = {};
  Object.keys(result).sort().forEach(k => {
    const zh = cleanZh(result[k].zh);
    if (!zh) return;
    const phon = String(result[k].phon || '').trim().replace(/\|/g, '');
    compact[k] = phon ? zh + '|' + phon : zh;
  });
  const block = BEGIN + '\n'
    + '// 题库全量单词的本地释义（' + Object.keys(compact).length + ' 词）。由本脚本生成，勿手改。\n'
    + '// 格式：word -> "短中文|音标"。Api._localDictBuild 会把它和词汇卡合并。\n'
    + 'const LOCAL_DICT = ' + JSON.stringify(compact) + ';\n' + END + '\n';
  let src = fs.readFileSync(API_FILE, 'utf8');
  const b = src.indexOf(BEGIN), e2 = src.indexOf(END);
  if (b >= 0 && e2 > b) src = src.slice(0, b) + block + src.slice(e2 + END.length + 1);
  else {
    const anchor = src.indexOf('const WordHelp = {');
    if (anchor < 0) throw new Error('WordHelp anchor not found');
    src = src.slice(0, anchor) + block + '\n' + src.slice(anchor);
  }
  fs.writeFileSync(API_FILE, src, 'utf8');
  console.log('已注入 api.js:', block.length, 'chars, api.js 现', fs.statSync(API_FILE).size, 'bytes');
}
main().catch(e => { console.error(e); process.exit(1); });
